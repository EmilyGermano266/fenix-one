create table if not exists public.sales_mobile_plans (
 id bigint generated by default as identity primary key,
 gb numeric not null unique,
 price_cents integer not null check(price_cents > 0),
 active boolean not null default true
);
insert into public.sales_mobile_plans (gb,price_cents,active) values
 (10,3000,true),(25,4000,true),(80,5500,true),(100,10000,true)
on conflict (gb) do nothing;
alter table public.sales_mobile_plans enable row level security;
grant select on public.sales_mobile_plans to authenticated;
grant update on public.sales_mobile_plans to authenticated;
create policy "v20 sales read" on public.sales_mobile_plans for select to authenticated using (true);
create policy "v20 sales supervisor update" on public.sales_mobile_plans for update to authenticated
 using (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='supervisora' and p.active=true))
 with check (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='supervisora' and p.active=true));
